#!/usr/bin/env node
/**
 * Packs the Werkbank into one small module  [WP2] — spec §8 „werkbank ≤ 9 KB gz“.
 *
 *   node scripts/pack-werkbank.mjs          writes js/werkbank/werkbank.pack.js
 *   node scripts/pack-werkbank.mjs --check  exits 1 when the committed pack is stale
 *
 * Sources stay the readable truth: js/werkbank/werkbank.js, body.js, languages.js, facade.js. The page
 * (js/main.js) only loads the pack. It reuses the comment/whitespace stripper of scripts/pack-gl.mjs
 * (no renaming). Local modules become scopes; their imports from shared modules (lib/, render/,
 * punze.js, sections/) are merged into the pack's own import lines, so those stay single instances.
 * One module instead of four also means no lazy sub-module can fail on its own (a dropped request
 * used to leave the Werkbank dead until reload). tests/werkbank.spec.js fails when the pack is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { fileURLToPath } from "node:url";
import { minify } from "./pack-gl.mjs";

const ROOT = new URL("../", import.meta.url);
const read = (p) => readFileSync(new URL(p, ROOT), "utf8");
export const OUT = "js/werkbank/werkbank.pack.js";
export const BUDGET = 9 * 1024;
const DIR = "js/werkbank/";
const ENTRY = "werkbank.js";
const LOCAL = new Set(["./body.js", "./languages.js", "./facade.js"]);
const IMPORT = /^import\s+(\*\s+as\s+([\w$]+)|\{([^}]*)\})\s+from\s+"([^"]+)";\n/gm;

const exportsOf = (src) => [...src.matchAll(/^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([\w$]+)/gm)].map((m) => m[1]);
const scopeId = (spec) => `__${spec.replace(/\W/g, "")}`;

/** Builds the pack source (string). */
export function pack() {
  const external = new Map(); // module → Map(local name → imported name)
  const scopes = [];
  const seen = new Set();

  function take(file) {
    let src = read(DIR + file);
    src = src.replace(IMPORT, (_, __, ns, names, from) => {
      if (LOCAL.has(from)) {
        load(from);
        return ns ? `const ${ns} = ${scopeId(from)};\n` : `const {${names.replace(/\bas\b/g, ":")}} = ${scopeId(from)};\n`;
      }
      if (!from.startsWith(".")) throw new Error(`pack-werkbank: bare import ${from}`);
      if (ns) throw new Error(`pack-werkbank: namespace import of shared ${from}`);
      const map = external.get(from) ?? new Map();
      for (const part of names.split(",").map((n) => n.trim()).filter(Boolean)) {
        const [imported, local = imported] = part.split(/\s+as\s+/);
        for (const [mod, m] of external) if (mod !== from && m.has(local)) throw new Error(`pack-werkbank: ${local} imported from ${mod} and ${from}`);
        map.set(local, imported);
      }
      external.set(from, map);
      return "";
    });
    if (/^import\s/m.test(src) || /\bimport\(\s*"\.\/(body|languages|facade)\.js"/.test(src)) throw new Error(`pack-werkbank: unhandled import in ${file}`);
    return src;
  }
  function load(spec) {
    if (seen.has(spec)) return;
    seen.add(spec);
    let src = take(spec.slice(2));
    const ex = exportsOf(src);
    src = src.replace(/^export\s+default\s+[\w$]+;\n?/gm, "").replace(/^export\s+/gm, "");
    scopes.push(`const ${scopeId(spec)}=(()=>{${minify(src)}\nreturn{${ex.join(",")}}})();`);
  }

  const entry = take(ENTRY);
  const imports = [...external]
    .map(([from, m]) => `import{${[...m].map(([local, imported]) => (local === imported ? local : `${imported} as ${local}`)).join(",")}}from"${from}";`)
    .join("\n");
  const head = `// Generated by scripts/pack-werkbank.mjs from js/werkbank/werkbank.js, body.js, languages.js, facade.js. Do not edit; edit the sources and re-run it.\n`;
  return head + imports + "\n" + scopes.join("\n") + "\n" + minify(entry) + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = pack();
  let cur = "";
  try {
    cur = read(OUT);
  } catch {
    /* first run */
  }
  const gz = gzipSync(next, { level: 9 }).length;
  if (process.argv.includes("--check")) {
    if (cur !== next) {
      console.error(`${OUT} is stale: run node scripts/pack-werkbank.mjs`);
      process.exit(1);
    }
    console.log(`${OUT} up to date (${next.length} B raw, ${gz} B gz, budget ${BUDGET})`);
  } else {
    writeFileSync(new URL(OUT, ROOT), next);
    console.log(`${OUT}: ${next.length} B raw, ${gz} B gz (budget ${BUDGET})`);
  }
  if (gz > BUDGET) process.exit(1);
}
