#!/usr/bin/env node
/**
 * scripts/make-zr-sprite.mjs — one sprite for the Zeitraffer's portfolio chips  [WP5]
 *
 * The chips in the „Im Portfolio“ lane are 40 × 25 CSS px. Loading a 640 w plate thumbnail for
 * each of them is ~60× the pixels they need, so this script packs every chip image (portfolio
 * projects that have a repo in data/repos.json) into one strip at 2× (80 × 50 px per cell,
 * centre-cropped to the chip's 16:10) and writes a tiny module the Zeitraffer reads:
 *
 *   assets/img/thumbs/zr-sprite.webp       one row, cell i at x = i × 80
 *   js/render/zr-sprite.js                 export const ZR_SPRITE = { src, n, cells: { "<image>": i } }
 *
 * Needs ffmpeg (compose) and cwebp (encode) on PATH. Originals are never touched.
 * Re-run after changing a project image or the repo mapping:  node scripts/make-zr-sprite.mjs
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, statSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const OUT = "assets/img/thumbs/zr-sprite.webp";
const CW = 80;
const CH = 50;

const read = (p) => JSON.parse(readFileSync(join(ROOT, p), "utf8"));
const rawProjects = read("data/projects.json");
const projects = Array.isArray(rawProjects) ? rawProjects : rawProjects.projects;
const rawRepos = read("data/repos.json");
const repoIds = new Set((Array.isArray(rawRepos) ? rawRepos : rawRepos.repos).filter((r) => r.id).map((r) => r.id));

/** Images in a stable order (sorted), so the sprite only changes when the set changes. */
export const spriteImages = () =>
  [...new Set(projects.filter((p) => repoIds.has(p.id) && p.image).map((p) => p.image))].filter((im) => existsSync(join(ROOT, im))).sort();

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const images = spriteImages();
  const tmp = mkdtempSync(join(tmpdir(), "zr-sprite-"));
  const png = join(tmp, "sprite.png");
  const inputs = images.flatMap((im) => ["-i", join(ROOT, im)]);
  const cells = images.map((_, i) => `[${i}:v]scale=${CW}:${CH}:force_original_aspect_ratio=increase:flags=lanczos,crop=${CW}:${CH},setsar=1[c${i}]`);
  const stack = images.length > 1 ? `${images.map((_, i) => `[c${i}]`).join("")}hstack=inputs=${images.length}[out]` : "[c0]copy[out]";
  execFileSync("ffmpeg", ["-v", "error", "-y", ...inputs, "-filter_complex", [...cells, stack].join(";"), "-map", "[out]", "-frames:v", "1", png]);
  execFileSync("cwebp", ["-quiet", "-q", "70", "-m", "6", "-sharp_yuv", png, "-o", join(ROOT, OUT)]);
  rmSync(tmp, { recursive: true, force: true });

  const map = Object.fromEntries(images.map((im, i) => [im, i]));
  const body = `/**
 * GENERATED by scripts/make-zr-sprite.mjs — do not edit by hand.
 * The Zeitraffer's portfolio chips: one strip of ${CW} × ${CH} px cells (2× the 40 × 25 chip).
 */
export const ZR_SPRITE = ${JSON.stringify({ src: OUT, n: images.length, cells: map })};
`;
  writeFileSync(join(ROOT, "js/render/zr-sprite.js"), body);
  console.log(`${images.length} chips → ${OUT} (${(statSync(join(ROOT, OUT)).size / 1024).toFixed(1)} KB)`);
}
